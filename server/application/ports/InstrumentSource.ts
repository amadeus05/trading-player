/**
 * Провайдер, который сам знает свой набор инструментов.
 *
 * У Bybit символов тысячи и спрашивать их незачем — тикер вводится руками. А у
 * архивного источника набор конечен, и интерфейсу нужен именно он, чтобы новый
 * инструмент выбирался в списке, а не добавлялся правкой кода.
 */
export interface InstrumentSource {
  symbols(): Promise<string[]>;
}
