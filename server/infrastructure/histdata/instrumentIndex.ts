/** Страница, на которой источник перечисляет всё, что отдаёт минутными архивами. */
export const INSTRUMENT_INDEX_PATH = "/download-free-forex-data/?/ascii/1-minute-bar-quotes";

/**
 * Коды инструментов со страницы списка HistData.
 *
 * Набор инструментов спрашивается у источника, а не хранится в коде: иначе
 * каждая новая пара означала бы правку файла и сборку приложения, а плеером
 * пользуются не программисты. Ссылки на страницы инструментов — единственное
 * место, где источник перечисляет свой набор целиком.
 *
 * Регистр здесь работает признаком: в ссылках списка коды заглавные, а строчные
 * встречаются в наших собственных адресах закачки, и путать их нельзя.
 */
export function parseHistDataInstruments(html: string): string[] {
  const codes = new Set<string>();
  for (const link of html.matchAll(/1-minute-bar-quotes\/([A-Z][A-Z0-9]{2,11})(?=["/])/g)) {
    codes.add(link[1]);
  }
  return [...codes].sort();
}
